pub mod pipeline_tb;

use std::fmt::Write;

use crate::ir::{BoundDfg, DfgOp};

pub fn generate_testbench(bound: &BoundDfg, _source: &str) -> String {
    let dfg = &bound.scheduled.dfg;
    let mut tb = String::with_capacity(8192);
    let mod_name = verilog_safe(&dfg.name);

    writeln!(tb, "// Co-simulation testbench for {}", dfg.name).unwrap();
    writeln!(tb, "// Generated by c2v — verifies Verilog matches C semantics").unwrap();
    writeln!(tb, "`timescale 1ns/1ps").unwrap();
    writeln!(tb).unwrap();
    writeln!(tb, "module tb_{mod_name};").unwrap();
    writeln!(tb).unwrap();
    writeln!(tb, "    reg clk, rst, start;").unwrap();
    writeln!(tb, "    wire done;").unwrap();

    for port in &dfg.inputs {
        writeln!(tb, "    reg  [{w}:0] {n};", w = port.width - 1, n = verilog_safe(&port.name)).unwrap();
    }
    for port in &dfg.outputs {
        writeln!(tb, "    wire [{w}:0] {n};", w = port.width - 1, n = verilog_safe(&port.name)).unwrap();
    }
    writeln!(tb).unwrap();

    // DUT instantiation
    writeln!(tb, "    {mod_name} dut(").unwrap();
    writeln!(tb, "        .clk(clk),").unwrap();
    writeln!(tb, "        .rst(rst),").unwrap();
    writeln!(tb, "        .start(start),").unwrap();
    writeln!(tb, "        .done(done),").unwrap();

    let all_ports: Vec<_> = dfg.inputs.iter().chain(dfg.outputs.iter()).collect();
    for (i, port) in all_ports.iter().enumerate() {
        let n = verilog_safe(&port.name);
        let comma = if i == all_ports.len() - 1 { "" } else { "," };
        writeln!(tb, "        .{n}({n}){comma}").unwrap();
    }
    writeln!(tb, "    );").unwrap();
    writeln!(tb).unwrap();

    // Reference arrays (for array-using functions)
    for arr in &dfg.arrays {
        let name = verilog_safe(&arr.name);
        writeln!(tb, "    reg [{w}:0] ref_{name} [0:{s}];",
            w = arr.elem_width - 1, s = arr.size - 1).unwrap();
    }

    writeln!(tb).unwrap();

    // Reference model
    if let Some(out_port) = dfg.outputs.first() {
        writeln!(tb, "    reg [{w}:0] expected;", w = out_port.width - 1).unwrap();
        writeln!(tb).unwrap();
    }

    // Clock
    writeln!(tb, "    always #5 clk = ~clk;").unwrap();
    writeln!(tb).unwrap();

    // Test procedure
    writeln!(tb, "    integer i, errors;").unwrap();
    writeln!(tb).unwrap();
    writeln!(tb, "    initial begin").unwrap();
    writeln!(tb, "        clk = 0; rst = 1; start = 0; errors = 0;").unwrap();
    writeln!(tb, "        @(posedge clk); @(posedge clk);").unwrap();
    writeln!(tb, "        rst = 0;").unwrap();
    writeln!(tb, "        @(posedge clk);").unwrap();
    writeln!(tb).unwrap();
    writeln!(tb, "        for (i = 0; i < 1000; i = i + 1) begin").unwrap();

    for port in &dfg.inputs {
        let n = verilog_safe(&port.name);
        if port.width > 32 {
            writeln!(tb, "            {n} = {{$urandom, $urandom}};").unwrap();
        } else {
            writeln!(tb, "            {n} = $urandom;").unwrap();
        }
    }

    // Populate reference arrays each iteration
    for node in &dfg.nodes {
        if let DfgOp::Store { array } = &node.op {
            let inputs: Vec<u32> = dfg.edges.iter()
                .filter(|e| e.to == node.id && e.width > 0)
                .map(|e| e.from).collect();
            if inputs.len() >= 2 {
                let name = verilog_safe(array);
                let idx_expr = expr_for_node(inputs[0], dfg);
                let val_expr = expr_for_node(inputs[1], dfg);
                writeln!(tb, "            ref_{name}[{idx_expr}] = {val_expr};").unwrap();
            }
        }
    }

    writeln!(tb).unwrap();
    writeln!(
        tb,
        "            expected = {};",
        build_reference_expr(bound)
    )
    .unwrap();
    writeln!(tb, "            start = 1;").unwrap();
    writeln!(tb, "            @(posedge clk);").unwrap();
    writeln!(tb, "            start = 0;").unwrap();
    writeln!(tb).unwrap();
    let wait_cycles = (bound.scheduled.total_cycles * 2) + 4;
    writeln!(tb, "            // Wait fixed number of cycles for FSM to complete").unwrap();
    writeln!(tb, "            repeat({wait_cycles}) @(posedge clk);").unwrap();
    writeln!(tb).unwrap();

    if let Some(out_port) = dfg.outputs.first() {
        let n = verilog_safe(&out_port.name);
        writeln!(tb, "            if ({n} !== expected) begin").unwrap();
        writeln!(tb, "                $display(\"MISMATCH at i=%0d: got=%0h expected=%0h\", i, {n}, expected);").unwrap();
        writeln!(tb, "                errors = errors + 1;").unwrap();
        writeln!(tb, "            end").unwrap();
    }

    writeln!(tb, "            @(posedge clk);").unwrap();
    writeln!(tb, "        end").unwrap();
    writeln!(tb).unwrap();
    writeln!(tb, "        if (errors == 0)").unwrap();
    writeln!(tb, "            $display(\"PASS: 1000/1000 vectors correct\");").unwrap();
    writeln!(tb, "        else").unwrap();
    writeln!(tb, "            $display(\"FAIL: %0d/1000 mismatches\", errors);").unwrap();
    writeln!(tb).unwrap();
    writeln!(tb, "        $finish;").unwrap();
    writeln!(tb, "    end").unwrap();
    writeln!(tb).unwrap();
    writeln!(tb, "endmodule").unwrap();

    tb
}

pub(crate) fn build_reference_expr(bound: &BoundDfg) -> String {
    let dfg = &bound.scheduled.dfg;

    if let Some(output_node) = dfg.nodes.iter().find(|n| matches!(&n.op, DfgOp::Output(_))) {
        let input_edge = dfg.edges.iter().find(|e| e.to == output_node.id);
        if let Some(edge) = input_edge {
            return expr_for_node(edge.from, dfg);
        }
    }

    "0".to_string()
}

pub(crate) fn expr_for_node(id: u32, dfg: &crate::ir::Dfg) -> String {
    let node = &dfg.nodes[id as usize];
    let inputs: Vec<u32> = dfg.edges.iter().filter(|e| e.to == id).map(|e| e.from).collect();

    match &node.op {
        DfgOp::Input(name) => verilog_safe(name),
        DfgOp::Const(val) => format!("{val}"),
        DfgOp::Add => binop_expr("+", &inputs, dfg),
        DfgOp::Sub => binop_expr("-", &inputs, dfg),
        DfgOp::Mul => binop_expr("*", &inputs, dfg),
        DfgOp::Div => binop_expr("/", &inputs, dfg),
        DfgOp::Mod => binop_expr("%", &inputs, dfg),
        DfgOp::Shl => binop_expr("<<", &inputs, dfg),
        DfgOp::Shr => binop_expr(">>", &inputs, dfg),
        DfgOp::And => binop_expr("&", &inputs, dfg),
        DfgOp::Or => binop_expr("|", &inputs, dfg),
        DfgOp::Xor => binop_expr("^", &inputs, dfg),
        DfgOp::Not => {
            if let Some(&a) = inputs.first() {
                format!("(~{})", expr_for_node(a, dfg))
            } else {
                "0".to_string()
            }
        }
        DfgOp::Eq => binop_expr("==", &inputs, dfg),
        DfgOp::Ne => binop_expr("!=", &inputs, dfg),
        DfgOp::Lt => binop_expr("<", &inputs, dfg),
        DfgOp::Gt => binop_expr(">", &inputs, dfg),
        DfgOp::Le => binop_expr("<=", &inputs, dfg),
        DfgOp::Ge => binop_expr(">=", &inputs, dfg),
        DfgOp::Mux => {
            if inputs.len() >= 3 {
                format!(
                    "({} ? {} : {})",
                    expr_for_node(inputs[0], dfg),
                    expr_for_node(inputs[1], dfg),
                    expr_for_node(inputs[2], dfg)
                )
            } else {
                "0".to_string()
            }
        }
        DfgOp::Load { array } => {
            let idx_inputs: Vec<u32> = dfg.edges.iter()
                .filter(|e| e.to == id && e.width > 0)
                .map(|e| e.from).collect();
            if let Some(&idx) = idx_inputs.first() {
                let name = verilog_safe(array);
                format!("ref_{name}[{}]", expr_for_node(idx, dfg))
            } else {
                "0".to_string()
            }
        }
        _ => "0".to_string(),
    }
}

fn binop_expr(op: &str, inputs: &[u32], dfg: &crate::ir::Dfg) -> String {
    if inputs.len() >= 2 {
        format!(
            "({} {} {})",
            expr_for_node(inputs[0], dfg),
            op,
            expr_for_node(inputs[1], dfg)
        )
    } else {
        "0".to_string()
    }
}

pub(crate) fn verilog_safe(name: &str) -> String {
    const RESERVED: &[&str] = &[
        "module", "endmodule", "input", "output", "wire", "reg", "integer",
        "parameter", "localparam", "assign", "always", "initial", "begin", "end",
        "if", "else", "case", "endcase", "default", "for", "while", "return",
        "function", "endfunction", "task", "endtask", "or", "and", "not", "xor",
        "table", "endtable", "event", "signed", "unsigned",
        "state", "clk", "rst", "done", "start", "valid_in", "valid_out",
    ];
    let sanitized: String = name.chars().map(|c| if c.is_alphanumeric() || c == '_' { c } else { '_' }).collect();
    if RESERVED.contains(&sanitized.as_str()) || sanitized.starts_with(|c: char| c.is_ascii_digit()) {
        format!("s_{sanitized}")
    } else {
        sanitized
    }
}
