use std::fmt::Write;

use crate::ir::BoundDfg;

pub fn generate_cocotb_test(bound: &BoundDfg) -> String {
    let dfg = &bound.scheduled.dfg;
    let mut out = String::with_capacity(4096);
    let mod_name = super::verilog_safe_name(&dfg.name);

    writeln!(out, "# Generated by c2v — cocotb testbench for {}", dfg.name).unwrap();
    writeln!(out, "# Run: make SIM=icarus TOPLEVEL={mod_name} MODULE=test_{mod_name}").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "import cocotb").unwrap();
    writeln!(out, "from cocotb.clock import Clock").unwrap();
    writeln!(out, "from cocotb.triggers import RisingEdge, Timer").unwrap();
    writeln!(out, "import random").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "@cocotb.test()").unwrap();
    writeln!(out, "async def test_{}(dut):", mod_name).unwrap();
    writeln!(out, "    clock = Clock(dut.clk, 10, units=\"ns\")").unwrap();
    writeln!(out, "    cocotb.start_soon(clock.start())").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "    # Reset").unwrap();
    writeln!(out, "    dut.rst.value = 1").unwrap();
    writeln!(out, "    dut.start.value = 0").unwrap();
    writeln!(out, "    for _ in range(3):").unwrap();
    writeln!(out, "        await RisingEdge(dut.clk)").unwrap();
    writeln!(out, "    dut.rst.value = 0").unwrap();
    writeln!(out, "    await RisingEdge(dut.clk)").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "    errors = 0").unwrap();
    writeln!(out, "    for i in range(1000):").unwrap();

    // Set random inputs
    for port in &dfg.inputs {
        let name = super::verilog_safe_name(&port.name);
        let max_val = if port.width >= 32 { "0xFFFFFFFF" } else { &format!("0x{:X}", (1u64 << port.width) - 1) };
        writeln!(out, "        {name}_val = random.randint(0, {max_val})").unwrap();
        writeln!(out, "        dut.{name}.value = {name}_val").unwrap();
    }

    writeln!(out).unwrap();
    writeln!(out, "        # Compute expected").unwrap();
    writeln!(out, "        # TODO: implement reference model in Python").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "        # Start computation").unwrap();
    writeln!(out, "        dut.start.value = 1").unwrap();
    writeln!(out, "        await RisingEdge(dut.clk)").unwrap();
    writeln!(out, "        dut.start.value = 0").unwrap();
    writeln!(out).unwrap();

    let wait = bound.scheduled.total_cycles * 2 + 5;
    writeln!(out, "        # Wait for completion").unwrap();
    writeln!(out, "        for _ in range({wait}):").unwrap();
    writeln!(out, "            await RisingEdge(dut.clk)").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "    dut._log.info(f\"Test complete: {{errors}}/1000 errors\")").unwrap();
    writeln!(out, "    assert errors == 0, f\"{{errors}} mismatches\"").unwrap();

    out
}

pub fn generate_makefile(mod_name: &str) -> String {
    let mut out = String::with_capacity(512);

    writeln!(out, "# Generated by c2v — cocotb Makefile").unwrap();
    writeln!(out, "SIM ?= icarus").unwrap();
    writeln!(out, "TOPLEVEL_LANG ?= verilog").unwrap();
    writeln!(out, "VERILOG_SOURCES = {mod_name}.v").unwrap();
    writeln!(out, "TOPLEVEL = {mod_name}").unwrap();
    writeln!(out, "MODULE = test_{mod_name}").unwrap();
    writeln!(out, "include $(shell cocotb-config --makefiles)/Makefile.sim").unwrap();

    out
}
