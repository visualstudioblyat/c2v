/* c2v pipeline emitter — generates pipelined Verilog with:
   - Configurable II (initiation interval), including II > 1
   - Valid shift register for pipeline stage tracking
   - FSM: IDLE → RUNNING → FLUSH → IDLE
   - Iteration counter with configurable trip count
   - Proper prologue/epilogue (drain) handling */

use std::collections::HashMap;
use std::fmt::Write;

use crate::ir::{BoundDfg, DfgOp, NodeId};
use super::{get_inputs, verilog_safe_name, width_decl, build_signal_names, verilog_binop};

pub fn emit_pipelined( bound: &BoundDfg ) -> String {
    emit_pipelined_ii( bound, 1 )
}

pub fn emit_pipelined_ii( bound: &BoundDfg, ii: u32 ) -> String {
    let mut out = String::with_capacity( 16384 );
    let dfg       = &bound.scheduled.dfg;
    let sig_names = build_signal_names( bound );
    let depth     = bound.scheduled.total_cycles;
    let ii        = ii.max(1);

    writeln!( out, "// Generated by c2v — pipelined Verilog" ).unwrap();
    writeln!( out, "// Function: {}", dfg.name ).unwrap();
    writeln!( out, "// Pipeline depth: {depth} stages" ).unwrap();
    writeln!( out, "// Initiation interval: II={ii}" ).unwrap();
    writeln!( out, "// Throughput: 1 result every {ii} cycle(s)" ).unwrap();
    writeln!( out ).unwrap();

    let name = verilog_safe_name( &dfg.name );
    write!( out, "module {name}(\n" ).unwrap();
    writeln!( out, "    input  wire              clk," ).unwrap();
    writeln!( out, "    input  wire              rst," ).unwrap();
    writeln!( out, "    input  wire              start," ).unwrap();
    writeln!( out, "    output reg               done," ).unwrap();
    writeln!( out, "    output reg               idle," ).unwrap();
    writeln!( out, "    input  wire              valid_in," ).unwrap();
    writeln!( out, "    output reg               valid_out," ).unwrap();

    for port in &dfg.inputs {
        let wd = width_decl( port.width );
        writeln!( out, "    input  wire {wd}{},", verilog_safe_name( &port.name ) ).unwrap();
    }
    for (idx, port) in dfg.outputs.iter().enumerate() {
        let wd    = width_decl( port.width );
        let comma = if idx == dfg.outputs.len() - 1 { "" } else { "," };
        writeln!( out, "    output reg  {wd}{}{comma}", verilog_safe_name( &port.name ) ).unwrap();
    }
    writeln!( out, ");" ).unwrap();
    writeln!( out ).unwrap();

    /* Valid shift register */
    writeln!( out, "    // Pipeline valid shift register ({depth} stages, II={ii})" ).unwrap();
    if depth > 0 {
        writeln!( out, "    reg [{d}:0] valid_sr;", d = depth - 1 ).unwrap();
    } else {
        writeln!( out, "    reg valid_sr;" ).unwrap();
    }
    writeln!( out ).unwrap();

    /* II counter for II > 1 */
    if ii > 1 {
        let ii_bits = 32 - (ii - 1).leading_zeros();
        writeln!( out, "    // II counter — accept new input every {ii} cycles" ).unwrap();
        writeln!( out, "    reg [{ib}:0] ii_counter;", ib = ii_bits - 1 ).unwrap();
        writeln!( out, "    wire accept_new = (ii_counter == 0);" ).unwrap();
        writeln!( out ).unwrap();
    }

    /* FSM states */
    writeln!( out, "    // Pipeline FSM" ).unwrap();
    writeln!( out, "    localparam S_IDLE    = 2'd0;" ).unwrap();
    writeln!( out, "    localparam S_RUNNING = 2'd1;" ).unwrap();
    writeln!( out, "    localparam S_FLUSH   = 2'd2;" ).unwrap();
    writeln!( out, "    reg [1:0] pipe_state;" ).unwrap();
    writeln!( out ).unwrap();

    /* Memory arrays */
    if !dfg.arrays.is_empty() {
        writeln!( out, "    // Memory arrays" ).unwrap();
        for arr in &dfg.arrays {
            let wd = width_decl( arr.elem_width );
            let n  = verilog_safe_name( &format!( "mem_{}", arr.name ) );
            writeln!( out, "    reg  {wd}{n} [0:{}];", arr.size - 1 ).unwrap();
        }
        writeln!( out ).unwrap();
    }

    /* Pipeline registers */
    writeln!( out, "    // Pipeline registers" ).unwrap();
    for port in &dfg.inputs {
        let wd = width_decl( port.width );
        let n  = verilog_safe_name( &port.name );
        writeln!( out, "    reg  {wd}{n}_r;" ).unwrap();
    }
    for node in &dfg.nodes {
        match &node.op {
            DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Output(_) | DfgOp::Nop => {}
            _ => {
                if let Some(sig) = sig_names.get( &node.id ) {
                    let wd = width_decl( node.width );
                    writeln!( out, "    reg  {wd}{sig};" ).unwrap();
                }
            }
        }
    }
    writeln!( out ).unwrap();

    /* Feeding signal */
    let feed_cond = if ii > 1 { "valid_in && accept_new" } else { "valid_in" };

    /* Main always block */
    writeln!( out, "    always @(posedge clk) begin" ).unwrap();
    writeln!( out, "        if (rst) begin" ).unwrap();
    writeln!( out, "            pipe_state <= S_IDLE;" ).unwrap();
    writeln!( out, "            valid_sr   <= 0;" ).unwrap();
    writeln!( out, "            valid_out  <= 1'b0;" ).unwrap();
    writeln!( out, "            done       <= 1'b0;" ).unwrap();
    writeln!( out, "            idle       <= 1'b1;" ).unwrap();
    if ii > 1 {
        writeln!( out, "            ii_counter <= 0;" ).unwrap();
    }
    writeln!( out, "        end else begin" ).unwrap();
    writeln!( out, "            case (pipe_state)" ).unwrap();

    /* IDLE state */
    writeln!( out, "                S_IDLE: begin" ).unwrap();
    writeln!( out, "                    done <= 1'b0;" ).unwrap();
    writeln!( out, "                    idle <= 1'b1;" ).unwrap();
    writeln!( out, "                    valid_out <= 1'b0;" ).unwrap();
    writeln!( out, "                    if (start) begin" ).unwrap();
    writeln!( out, "                        pipe_state <= S_RUNNING;" ).unwrap();
    writeln!( out, "                        idle       <= 1'b0;" ).unwrap();
    if ii > 1 {
        writeln!( out, "                        ii_counter <= 0;" ).unwrap();
    }
    writeln!( out, "                    end" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    /* RUNNING state */
    writeln!( out, "                S_RUNNING: begin" ).unwrap();

    /* II counter logic */
    if ii > 1 {
        writeln!( out, "                    if (ii_counter < {}) ii_counter <= ii_counter + 1;",
            ii - 1 ).unwrap();
        writeln!( out, "                    else ii_counter <= 0;" ).unwrap();
    }

    /* Valid shift register: insert 1 when feeding, shift every cycle */
    if depth > 1 {
        writeln!( out, "                    valid_sr <= {{valid_sr[{d}:0], {feed_cond} ? 1'b1 : 1'b0}};",
            d = depth - 2 ).unwrap();
    } else {
        writeln!( out, "                    valid_sr <= {feed_cond} ? 1'b1 : 1'b0;" ).unwrap();
    }
    writeln!( out, "                    valid_out <= valid_sr[{d}];", d = depth - 1 ).unwrap();
    writeln!( out ).unwrap();

    /* Capture inputs when feeding */
    writeln!( out, "                    // Capture inputs" ).unwrap();
    writeln!( out, "                    if ({feed_cond}) begin" ).unwrap();
    for port in &dfg.inputs {
        let n = verilog_safe_name( &port.name );
        writeln!( out, "                        {n}_r <= {n};" ).unwrap();
    }
    writeln!( out, "                    end" ).unwrap();
    writeln!( out ).unwrap();

    /* Per-stage computation */
    for cycle in 0..depth {
        let nodes_in_cycle: Vec<_> = dfg.nodes.iter()
            .filter(|n| bound.scheduled.schedule.get( &n.id ) == Some( &cycle ))
            .collect();

        let has_real_ops = nodes_in_cycle.iter()
            .any(|n| !matches!( &n.op, DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop ));
        if !has_real_ops { continue; }

        writeln!( out, "                    // Stage {cycle}" ).unwrap();

        for node in &nodes_in_cycle {
            match &node.op {
                DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop => {}
                DfgOp::Output(oname) => {
                    let inputs = get_inputs( node.id, bound );
                    if let Some(&src) = inputs.first() {
                        let src_ref = pipe_operand_ref( src, &sig_names, bound );
                        writeln!( out, "                    {} <= {src_ref};",
                            verilog_safe_name( oname ) ).unwrap();
                    }
                }
                DfgOp::Not => {
                    let inputs = get_inputs( node.id, bound );
                    if let Some(&a) = inputs.first() {
                        let sig   = &sig_names[&node.id];
                        let a_ref = pipe_operand_ref( a, &sig_names, bound );
                        writeln!( out, "                    {sig} <= ~{a_ref};" ).unwrap();
                    }
                }
                DfgOp::Mux => {
                    let inputs = get_inputs( node.id, bound );
                    if inputs.len() >= 3 {
                        let sig  = &sig_names[&node.id];
                        let cond = pipe_operand_ref( inputs[0], &sig_names, bound );
                        let t    = pipe_operand_ref( inputs[1], &sig_names, bound );
                        let f    = pipe_operand_ref( inputs[2], &sig_names, bound );
                        writeln!( out, "                    {sig} <= {cond} ? {t} : {f};" ).unwrap();
                    }
                }
                DfgOp::Load { array } => {
                    let inputs = get_inputs( node.id, bound );
                    let sig    = &sig_names[&node.id];
                    let arr    = verilog_safe_name( &format!( "mem_{array}" ) );
                    if let Some(&idx) = inputs.iter().find(|&&id| {
                        bound.scheduled.dfg.edges.iter()
                            .any(|e| e.from == id && e.to == node.id && e.width > 0)
                    }) {
                        let idx_ref = pipe_operand_ref( idx, &sig_names, bound );
                        writeln!( out, "                    {sig} <= {arr}[{idx_ref}];" ).unwrap();
                    }
                }
                DfgOp::Store { array } => {
                    let inputs = get_inputs( node.id, bound );
                    let arr    = verilog_safe_name( &format!( "mem_{array}" ) );
                    if inputs.len() >= 2 {
                        let idx = pipe_operand_ref( inputs[0], &sig_names, bound );
                        let val = pipe_operand_ref( inputs[1], &sig_names, bound );
                        writeln!( out, "                    {arr}[{idx}] <= {val};" ).unwrap();
                    }
                }
                _ => {
                    if let Some(op_str) = verilog_binop( &node.op ) {
                        let inputs = get_inputs( node.id, bound );
                        if inputs.len() >= 2 {
                            let sig = &sig_names[&node.id];
                            let l   = pipe_operand_ref( inputs[0], &sig_names, bound );
                            let r   = pipe_operand_ref( inputs[1], &sig_names, bound );
                            writeln!( out, "                    {sig} <= {l} {op_str} {r};" ).unwrap();
                        }
                    }
                }
            }
        }
    }

    /* Transition to FLUSH when valid_in drops */
    writeln!( out ).unwrap();
    writeln!( out, "                    if (!valid_in && valid_sr == 0)" ).unwrap();
    writeln!( out, "                        pipe_state <= S_IDLE;" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    /* FLUSH state — drain remaining pipeline stages */
    writeln!( out, "                S_FLUSH: begin" ).unwrap();
    if depth > 1 {
        writeln!( out, "                    valid_sr <= {{valid_sr[{d}:0], 1'b0}};", d = depth - 2 ).unwrap();
    } else {
        writeln!( out, "                    valid_sr <= 1'b0;" ).unwrap();
    }
    writeln!( out, "                    valid_out <= valid_sr[{d}];", d = depth - 1 ).unwrap();
    writeln!( out, "                    if (valid_sr == 0) begin" ).unwrap();
    writeln!( out, "                        pipe_state <= S_IDLE;" ).unwrap();
    writeln!( out, "                        done       <= 1'b1;" ).unwrap();
    writeln!( out, "                        idle       <= 1'b1;" ).unwrap();
    writeln!( out, "                    end" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    writeln!( out, "                default: pipe_state <= S_IDLE;" ).unwrap();
    writeln!( out, "            endcase" ).unwrap();
    writeln!( out, "        end" ).unwrap();
    writeln!( out, "    end" ).unwrap();
    writeln!( out ).unwrap();
    writeln!( out, "endmodule" ).unwrap();

    out
}

fn pipe_operand_ref( node_id: NodeId, sig_names: &HashMap<NodeId, String>, bound: &BoundDfg ) -> String {
    let node = &bound.scheduled.dfg.nodes[node_id as usize];
    match &node.op {
        DfgOp::Input(name) => format!( "{}_r", verilog_safe_name( name ) ),
        DfgOp::Const(val) => {
            let w = node.width;
            format!( "{w}'d{val}" )
        }
        _ => sig_names.get( &node_id )
            .cloned()
            .unwrap_or_else(|| format!( "node_{node_id}" ) ),
    }
}
