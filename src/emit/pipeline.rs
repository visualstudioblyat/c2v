use std::collections::HashMap;
use std::fmt::Write;

use crate::ir::{BoundDfg, DfgOp, NodeId};
use super::{get_inputs, operand_ref, verilog_safe_name, width_decl, build_signal_names, verilog_binop, state_width};

pub fn emit_pipelined(bound: &BoundDfg) -> String {
    let mut out = String::with_capacity(16384);
    let dfg = &bound.scheduled.dfg;
    let sig_names = build_signal_names(bound);
    let total_stages = bound.scheduled.total_cycles;

    writeln!(out, "// Generated by c2v — Firedancer-style C to Verilog (PIPELINED)").unwrap();
    writeln!(out, "// Source function: {}", dfg.name).unwrap();
    writeln!(out, "// Pipeline stages: {total_stages}").unwrap();
    writeln!(out, "// Initiation interval: II=1 (new input every clock)").unwrap();
    writeln!(out, "// Resources: {} units", bound.resources.len()).unwrap();
    writeln!(out).unwrap();

    // Module declaration
    write!(out, "module {name}(\n", name = verilog_safe_name(&dfg.name)).unwrap();
    writeln!(out, "    input  wire              clk,").unwrap();
    writeln!(out, "    input  wire              rst,").unwrap();
    writeln!(out, "    input  wire              valid_in,").unwrap();
    writeln!(out, "    output reg               valid_out,").unwrap();

    for port in &dfg.inputs {
        let wd = width_decl(port.width);
        writeln!(out, "    input  wire {wd}{},", verilog_safe_name(&port.name)).unwrap();
    }

    for (idx, port) in dfg.outputs.iter().enumerate() {
        let wd = width_decl(port.width);
        let comma = if idx == dfg.outputs.len() - 1 { "" } else { "," };
        writeln!(out, "    output reg  {wd}{}{comma}", verilog_safe_name(&port.name)).unwrap();
    }

    writeln!(out, ");").unwrap();
    writeln!(out).unwrap();

    // Valid pipeline shift register
    writeln!(out, "    // Valid pipeline ({total_stages} stage latency)").unwrap();
    writeln!(out, "    reg [{s}:0] valid_sr;", s = total_stages - 1).unwrap();
    writeln!(out).unwrap();

    // Memory arrays
    if !dfg.arrays.is_empty() {
        writeln!(out, "    // Memory arrays").unwrap();
        for arr in &dfg.arrays {
            let wd = width_decl(arr.elem_width);
            let name = verilog_safe_name(&format!("mem_{}", arr.name));
            writeln!(out, "    reg  {wd}{name} [0:{}];", arr.size - 1).unwrap();
        }
        writeln!(out).unwrap();
    }

    // Pipeline registers: each intermediate value gets a register per stage it lives through
    writeln!(out, "    // Pipeline registers").unwrap();

    // Input capture registers
    for port in &dfg.inputs {
        let wd = width_decl(port.width);
        let name = verilog_safe_name(&port.name);
        writeln!(out, "    reg  {wd}{name}_r;").unwrap();
    }

    // Computation registers
    for node in &dfg.nodes {
        match &node.op {
            DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Output(_) | DfgOp::Nop => {}
            _ => {
                if let Some(sig) = sig_names.get(&node.id) {
                    let wd = width_decl(node.width);
                    writeln!(out, "    reg  {wd}{sig};").unwrap();
                }
            }
        }
    }
    writeln!(out).unwrap();

    // Pipeline always block
    writeln!(out, "    always @(posedge clk) begin").unwrap();
    writeln!(out, "        if (rst) begin").unwrap();
    writeln!(out, "            valid_sr  <= 0;").unwrap();
    writeln!(out, "            valid_out <= 1'b0;").unwrap();
    writeln!(out, "        end else begin").unwrap();

    // Shift valid pipeline
    if total_stages > 1 {
        writeln!(out, "            valid_sr  <= {{valid_sr[{s}:0], valid_in}};", s = total_stages - 2).unwrap();
    } else {
        writeln!(out, "            valid_sr  <= valid_in;").unwrap();
    }
    writeln!(out, "            valid_out <= valid_sr[{s}];", s = total_stages - 1).unwrap();
    writeln!(out).unwrap();

    // Capture inputs
    for port in &dfg.inputs {
        let name = verilog_safe_name(&port.name);
        writeln!(out, "            {name}_r <= {name};").unwrap();
    }
    writeln!(out).unwrap();

    // Emit computation for each stage
    for cycle in 0..total_stages {
        let nodes_in_cycle: Vec<_> = dfg.nodes.iter().filter(|n| {
            bound.scheduled.schedule.get(&n.id) == Some(&cycle)
        }).collect();

        if nodes_in_cycle.iter().any(|n| !matches!(&n.op, DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop)) {
            writeln!(out, "            // Stage {cycle}").unwrap();
        }

        for node in &nodes_in_cycle {
            match &node.op {
                DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop => {}
                DfgOp::Output(name) => {
                    let inputs = get_inputs(node.id, bound);
                    if let Some(&src) = inputs.first() {
                        let src_ref = pipe_operand_ref(src, cycle, &sig_names, bound);
                        writeln!(out, "            {} <= {src_ref};", verilog_safe_name(name)).unwrap();
                    }
                }
                DfgOp::Not => {
                    let inputs = get_inputs(node.id, bound);
                    if let Some(&a) = inputs.first() {
                        let sig = &sig_names[&node.id];
                        let a_ref = pipe_operand_ref(a, cycle, &sig_names, bound);
                        writeln!(out, "            {sig} <= ~{a_ref};").unwrap();
                    }
                }
                DfgOp::Load { array } => {
                    let inputs = get_inputs(node.id, bound);
                    let sig = &sig_names[&node.id];
                    let arr_name = verilog_safe_name(&format!("mem_{array}"));
                    if let Some(&idx) = inputs.iter().find(|&&id| {
                        bound.scheduled.dfg.edges.iter().any(|e| e.from == id && e.to == node.id && e.width > 0)
                    }) {
                        let idx_ref = pipe_operand_ref(idx, cycle, &sig_names, bound);
                        writeln!(out, "            {sig} <= {arr_name}[{idx_ref}];").unwrap();
                    }
                }
                DfgOp::Store { array } => {
                    let inputs = get_inputs(node.id, bound);
                    let arr_name = verilog_safe_name(&format!("mem_{array}"));
                    if inputs.len() >= 2 {
                        let idx_ref = pipe_operand_ref(inputs[0], cycle, &sig_names, bound);
                        let val_ref = pipe_operand_ref(inputs[1], cycle, &sig_names, bound);
                        writeln!(out, "            {arr_name}[{idx_ref}] <= {val_ref};").unwrap();
                    }
                }
                _ => {
                    if let Some(op_str) = verilog_binop(&node.op) {
                        let inputs = get_inputs(node.id, bound);
                        if inputs.len() >= 2 {
                            let sig = &sig_names[&node.id];
                            let left = pipe_operand_ref(inputs[0], cycle, &sig_names, bound);
                            let right = pipe_operand_ref(inputs[1], cycle, &sig_names, bound);
                            writeln!(out, "            {sig} <= {left} {op_str} {right};").unwrap();
                        }
                    }
                }
            }
        }
    }

    writeln!(out, "        end").unwrap();
    writeln!(out, "    end").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "endmodule").unwrap();

    out
}

fn pipe_operand_ref(node_id: NodeId, _cur_cycle: u32, sig_names: &HashMap<NodeId, String>, bound: &BoundDfg) -> String {
    let node = &bound.scheduled.dfg.nodes[node_id as usize];
    match &node.op {
        DfgOp::Input(name) => format!("{}_r", verilog_safe_name(name)),
        DfgOp::Const(val) => {
            let w = node.width;
            format!("{w}'d{val}")
        }
        _ => sig_names.get(&node_id).cloned().unwrap_or_else(|| format!("node_{node_id}")),
    }
}
