/* c2v_loop_pipeline emits a pipelined loop as Verilog. Given:
   - A scheduled single-iteration body DFG
   - Initiation interval (II)
   - Trip count (or parameterized N)

   It produces a module with:
   - Iteration counter (0..N-1)
   - Valid shift register (depth = body latency)
   - II counter (for II > 1)
   - Per-stage computation from the body schedule
   - Start/done/idle control signals

   The key insight: the body DFG is scheduled as if it were a
   standalone function. The loop wrapper just feeds it with
   new inputs every II cycles and tracks completion. */

use std::collections::HashMap;
use std::fmt::Write;

use crate::ir::{BoundDfg, DfgOp, NodeId};
use super::{get_inputs, verilog_safe_name, width_decl, build_signal_names,
            verilog_binop, operand_ref};

pub struct LoopPipelineConfig {
    pub ii:             u32,
    pub trip_count:     u32,
    pub param_trip:     bool,
}

impl Default for LoopPipelineConfig {
    fn default() -> Self {
        Self { ii: 1, trip_count: 1024, param_trip: true }
    }
}

pub fn emit_loop_pipeline( bound: &BoundDfg, config: &LoopPipelineConfig ) -> String {
    let mut out = String::with_capacity( 16384 );
    let dfg       = &bound.scheduled.dfg;
    let sig_names = build_signal_names( bound );
    let depth     = bound.scheduled.total_cycles;
    let ii        = config.ii.max(1);
    let name      = verilog_safe_name( &dfg.name );

    let trip_param = if config.param_trip { "N" } else { &config.trip_count.to_string() };
    let iter_bits  = if config.param_trip { 16 } else {
        (32 - config.trip_count.leading_zeros()).max(1)
    };

    writeln!( out, "// Generated by c2v — pipelined loop" ).unwrap();
    writeln!( out, "// Function: {}", dfg.name ).unwrap();
    writeln!( out, "// Body latency: {depth} cycles" ).unwrap();
    writeln!( out, "// Initiation interval: II={ii}" ).unwrap();
    writeln!( out, "// Trip count: {trip_param}" ).unwrap();
    writeln!( out, "// Total cycles: ({trip_param}-1)*{ii} + {depth}" ).unwrap();
    writeln!( out, "// Throughput: 1 result every {ii} cycle(s)" ).unwrap();
    writeln!( out ).unwrap();

    /* Module declaration */
    if config.param_trip {
        writeln!( out, "module {name} #(" ).unwrap();
        writeln!( out, "    parameter N = {}", config.trip_count ).unwrap();
        writeln!( out, ")(" ).unwrap();
    } else {
        writeln!( out, "module {name}(" ).unwrap();
    }
    writeln!( out, "    input  wire              clk," ).unwrap();
    writeln!( out, "    input  wire              rst," ).unwrap();
    writeln!( out, "    input  wire              start," ).unwrap();
    writeln!( out, "    output reg               done," ).unwrap();
    writeln!( out, "    output reg               idle," ).unwrap();

    for port in &dfg.inputs {
        let wd = width_decl( port.width );
        writeln!( out, "    input  wire {wd}{},", verilog_safe_name( &port.name ) ).unwrap();
    }
    for (idx, port) in dfg.outputs.iter().enumerate() {
        let wd    = width_decl( port.width );
        let comma = if idx == dfg.outputs.len() - 1 { "" } else { "," };
        writeln!( out, "    output reg  {wd}{}{comma}", verilog_safe_name( &port.name ) ).unwrap();
    }
    writeln!( out, ");" ).unwrap();
    writeln!( out ).unwrap();

    /* Valid shift register */
    writeln!( out, "    // Pipeline valid ({depth} stages, II={ii})" ).unwrap();
    writeln!( out, "    reg [{d}:0] valid_sr;", d = depth.max(1) - 1 ).unwrap();
    writeln!( out, "    wire        valid_out_w = valid_sr[{d}];", d = depth.max(1) - 1 ).unwrap();
    writeln!( out ).unwrap();

    /* Iteration counter */
    writeln!( out, "    // Iteration counter" ).unwrap();
    writeln!( out, "    reg [{ib}:0] iter_count;", ib = iter_bits - 1 ).unwrap();
    writeln!( out, "    wire         feeding = (iter_count < {trip_param});" ).unwrap();
    writeln!( out ).unwrap();

    /* II counter */
    if ii > 1 {
        let ii_bits = (32 - (ii - 1).leading_zeros()).max(1);
        writeln!( out, "    // II counter — new input every {ii} cycles" ).unwrap();
        writeln!( out, "    reg [{ib}:0] ii_counter;", ib = ii_bits - 1 ).unwrap();
        writeln!( out, "    wire         accept = (ii_counter == 0) && feeding;" ).unwrap();
        writeln!( out ).unwrap();
    } else {
        writeln!( out, "    wire accept = feeding;" ).unwrap();
        writeln!( out ).unwrap();
    }

    /* FSM */
    writeln!( out, "    // FSM" ).unwrap();
    writeln!( out, "    localparam S_IDLE = 2'd0, S_RUN = 2'd1, S_FLUSH = 2'd2;" ).unwrap();
    writeln!( out, "    reg [1:0] state;" ).unwrap();
    writeln!( out ).unwrap();

    /* Pipeline registers */
    writeln!( out, "    // Pipeline registers" ).unwrap();
    for port in &dfg.inputs {
        let wd = width_decl( port.width );
        let n  = verilog_safe_name( &port.name );
        writeln!( out, "    reg  {wd}{n}_r;" ).unwrap();
    }
    for node in &dfg.nodes {
        match &node.op {
            DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Output(_) | DfgOp::Nop => {}
            _ => {
                if let Some(sig) = sig_names.get( &node.id ) {
                    let wd   = width_decl( node.width );
                    let sign = if node.signed { "signed " } else { "" };
                    writeln!( out, "    reg  {sign}{wd}{sig};" ).unwrap();
                }
            }
        }
    }
    writeln!( out ).unwrap();

    /* Main always block */
    writeln!( out, "    always @(posedge clk) begin" ).unwrap();
    writeln!( out, "        if (rst) begin" ).unwrap();
    writeln!( out, "            state      <= S_IDLE;" ).unwrap();
    writeln!( out, "            valid_sr   <= 0;" ).unwrap();
    writeln!( out, "            iter_count <= 0;" ).unwrap();
    writeln!( out, "            done       <= 1'b0;" ).unwrap();
    writeln!( out, "            idle       <= 1'b1;" ).unwrap();
    if ii > 1 {
        writeln!( out, "            ii_counter <= 0;" ).unwrap();
    }
    writeln!( out, "        end else begin" ).unwrap();
    writeln!( out, "            case (state)" ).unwrap();

    /* IDLE */
    writeln!( out, "                S_IDLE: begin" ).unwrap();
    writeln!( out, "                    done <= 1'b0;" ).unwrap();
    writeln!( out, "                    idle <= 1'b1;" ).unwrap();
    writeln!( out, "                    if (start) begin" ).unwrap();
    writeln!( out, "                        state      <= S_RUN;" ).unwrap();
    writeln!( out, "                        iter_count <= 0;" ).unwrap();
    writeln!( out, "                        idle       <= 1'b0;" ).unwrap();
    if ii > 1 {
        writeln!( out, "                        ii_counter <= 0;" ).unwrap();
    }
    writeln!( out, "                    end" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    /* RUN */
    writeln!( out, "                S_RUN: begin" ).unwrap();

    /* II counter */
    if ii > 1 {
        writeln!( out, "                    if (ii_counter < {}) ii_counter <= ii_counter + 1;",
            ii - 1 ).unwrap();
        writeln!( out, "                    else ii_counter <= 0;" ).unwrap();
    }

    /* Valid shift register */
    if depth > 1 {
        writeln!( out, "                    valid_sr <= {{valid_sr[{d}:0], accept ? 1'b1 : 1'b0}};",
            d = depth - 2 ).unwrap();
    } else {
        writeln!( out, "                    valid_sr <= accept ? 1'b1 : 1'b0;" ).unwrap();
    }

    /* Iteration counter increment */
    writeln!( out, "                    if (accept) begin" ).unwrap();
    writeln!( out, "                        iter_count <= iter_count + 1;" ).unwrap();
    for port in &dfg.inputs {
        let n = verilog_safe_name( &port.name );
        writeln!( out, "                        {n}_r <= {n};" ).unwrap();
    }
    writeln!( out, "                    end" ).unwrap();
    writeln!( out ).unwrap();

    /* Per-stage computation */
    for cycle in 0..depth {
        let nodes_in_cycle: Vec<_> = dfg.nodes.iter()
            .filter(|n| bound.scheduled.schedule.get( &n.id ) == Some( &cycle ))
            .collect();

        let has_ops = nodes_in_cycle.iter()
            .any(|n| !matches!( &n.op, DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop ));
        if !has_ops { continue; }

        writeln!( out, "                    // Stage {cycle}" ).unwrap();
        for node in &nodes_in_cycle {
            emit_node_op( &mut out, node, bound, &sig_names, "                    " );
        }
    }

    /* Transition to flush */
    writeln!( out ).unwrap();
    writeln!( out, "                    if (!feeding && valid_sr == 0) begin" ).unwrap();
    writeln!( out, "                        state <= S_IDLE;" ).unwrap();
    writeln!( out, "                        done  <= 1'b1;" ).unwrap();
    writeln!( out, "                        idle  <= 1'b1;" ).unwrap();
    writeln!( out, "                    end else if (!feeding) begin" ).unwrap();
    writeln!( out, "                        state <= S_FLUSH;" ).unwrap();
    writeln!( out, "                    end" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    /* FLUSH */
    writeln!( out, "                S_FLUSH: begin" ).unwrap();
    if depth > 1 {
        writeln!( out, "                    valid_sr <= {{valid_sr[{d}:0], 1'b0}};", d = depth - 2 ).unwrap();
    } else {
        writeln!( out, "                    valid_sr <= 1'b0;" ).unwrap();
    }

    /* Repeat stage computation during flush for in-flight data */
    for cycle in 0..depth {
        let nodes_in_cycle: Vec<_> = dfg.nodes.iter()
            .filter(|n| bound.scheduled.schedule.get( &n.id ) == Some( &cycle ))
            .collect();
        let has_ops = nodes_in_cycle.iter()
            .any(|n| !matches!( &n.op, DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop ));
        if !has_ops { continue; }
        for node in &nodes_in_cycle {
            emit_node_op( &mut out, node, bound, &sig_names, "                    " );
        }
    }

    writeln!( out, "                    if (valid_sr == 0) begin" ).unwrap();
    writeln!( out, "                        state <= S_IDLE;" ).unwrap();
    writeln!( out, "                        done  <= 1'b1;" ).unwrap();
    writeln!( out, "                        idle  <= 1'b1;" ).unwrap();
    writeln!( out, "                    end" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    writeln!( out, "                default: state <= S_IDLE;" ).unwrap();
    writeln!( out, "            endcase" ).unwrap();
    writeln!( out, "        end" ).unwrap();
    writeln!( out, "    end" ).unwrap();
    writeln!( out ).unwrap();
    writeln!( out, "endmodule" ).unwrap();

    out
}

fn emit_node_op(
    out: &mut String,
    node: &crate::ir::DfgNode,
    bound: &BoundDfg,
    sig_names: &HashMap<NodeId, String>,
    indent: &str,
) {
    match &node.op {
        DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop => {}
        DfgOp::Output(oname) => {
            let inputs = get_inputs( node.id, bound );
            if let Some(&src) = inputs.first() {
                let src_ref = pipe_ref( src, sig_names, bound );
                writeln!( out, "{indent}{} <= {src_ref};",
                    verilog_safe_name( oname ) ).unwrap();
            }
        }
        DfgOp::Not => {
            let inputs = get_inputs( node.id, bound );
            if let Some(&a) = inputs.first() {
                let sig = &sig_names[&node.id];
                let a_ref = pipe_ref( a, sig_names, bound );
                writeln!( out, "{indent}{sig} <= ~{a_ref};" ).unwrap();
            }
        }
        DfgOp::Mux => {
            let inputs = get_inputs( node.id, bound );
            if inputs.len() >= 3 {
                let sig  = &sig_names[&node.id];
                let cond = pipe_ref( inputs[0], sig_names, bound );
                let t    = pipe_ref( inputs[1], sig_names, bound );
                let f    = pipe_ref( inputs[2], sig_names, bound );
                writeln!( out, "{indent}{sig} <= {cond} ? {t} : {f};" ).unwrap();
            }
        }
        DfgOp::Load { array } => {
            let inputs = get_inputs( node.id, bound );
            let sig    = &sig_names[&node.id];
            let arr    = verilog_safe_name( &format!( "mem_{array}" ) );
            if let Some(&idx) = inputs.iter().find(|&&id| {
                bound.scheduled.dfg.edges.iter()
                    .any(|e| e.from == id && e.to == node.id && e.width > 0)
            }) {
                let idx_ref = pipe_ref( idx, sig_names, bound );
                writeln!( out, "{indent}{sig} <= {arr}[{idx_ref}];" ).unwrap();
            }
        }
        DfgOp::Store { array } => {
            let inputs = get_inputs( node.id, bound );
            let arr    = verilog_safe_name( &format!( "mem_{array}" ) );
            if inputs.len() >= 2 {
                let idx = pipe_ref( inputs[0], sig_names, bound );
                let val = pipe_ref( inputs[1], sig_names, bound );
                writeln!( out, "{indent}{arr}[{idx}] <= {val};" ).unwrap();
            }
        }
        _ => {
            if let Some(op_str) = verilog_binop( &node.op ) {
                let inputs = get_inputs( node.id, bound );
                if inputs.len() >= 2 {
                    let sig = &sig_names[&node.id];
                    let l   = pipe_ref( inputs[0], sig_names, bound );
                    let r   = pipe_ref( inputs[1], sig_names, bound );
                    writeln!( out, "{indent}{sig} <= {l} {op_str} {r};" ).unwrap();
                }
            }
        }
    }
}

fn pipe_ref( node_id: NodeId, sig_names: &HashMap<NodeId, String>, bound: &BoundDfg ) -> String {
    let node = &bound.scheduled.dfg.nodes[node_id as usize];
    match &node.op {
        DfgOp::Input(name) => format!( "{}_r", verilog_safe_name( name ) ),
        DfgOp::Const(val) => {
            let w = node.width;
            format!( "{w}'d{val}" )
        }
        _ => sig_names.get( &node_id )
            .cloned()
            .unwrap_or_else(|| format!( "node_{node_id}" ) ),
    }
}
