/* c2v_vivado generates Xilinx Vivado project TCL scripts. Running the
   generated script creates a complete Vivado project with the c2v output
   Verilog, timing constraints, and synthesis settings. The user can then
   open the project in Vivado and run synthesis/implementation/bitstream
   with a single click, or source the script in batch mode:

     vivado -mode batch -source project.tcl

   The generated project targets a specific device and includes the
   AXI-Stream wrapper if requested. */

use std::fmt::Write;

use crate::ir::BoundDfg;

/* c2v_vivado_emit_tcl generates the Vivado project creation TCL.
   device_part is the full Xilinx part number (e.g. "xc7a35tcpg236-1").
   verilog_files is the list of .v files to include. */

pub fn emit_vivado_tcl(
    bound:         &BoundDfg,
    device_part:   &str,
    verilog_files: &[String],
    project_name:  &str,
    freq_mhz:      f64,
) -> String {
    let mut out = String::with_capacity( 4096 );
    let mod_name = super::verilog_safe_name( &bound.scheduled.dfg.name );

    writeln!( out, "# Generated by c2v — Vivado project script" ).unwrap();
    writeln!( out, "# Run: vivado -mode batch -source {project_name}.tcl" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "create_project {project_name} ./{project_name} -part {device_part} -force" ).unwrap();
    writeln!( out, "set_property target_language Verilog [current_project]" ).unwrap();
    writeln!( out ).unwrap();

    /* Add source files */
    writeln!( out, "# Add Verilog sources" ).unwrap();
    for f in verilog_files {
        writeln!( out, "add_files -norecurse {f}" ).unwrap();
    }
    writeln!( out ).unwrap();

    /* Set top module */
    writeln!( out, "set_property top {mod_name} [current_fileset]" ).unwrap();
    writeln!( out ).unwrap();

    /* Timing constraints */
    let period_ns = 1000.0 / freq_mhz;
    writeln!( out, "# Timing constraints" ).unwrap();
    writeln!( out, "create_clock -period {period_ns:.3} -name clk [get_ports clk]" ).unwrap();
    writeln!( out ).unwrap();

    /* Synthesis settings */
    writeln!( out, "# Synthesis settings" ).unwrap();
    writeln!( out, "set_property STEPS.SYNTH_DESIGN.ARGS.RETIMING true [get_runs synth_1]" ).unwrap();
    writeln!( out, "set_property STEPS.SYNTH_DESIGN.ARGS.FLATTEN_HIERARCHY rebuilt [get_runs synth_1]" ).unwrap();
    writeln!( out ).unwrap();

    /* Run synthesis */
    writeln!( out, "# Run synthesis" ).unwrap();
    writeln!( out, "launch_runs synth_1 -jobs [expr {{[get_property NUM_CPUS [get_hw_targets]] > 0 ? [get_property NUM_CPUS [get_hw_targets]] : 4}}]" ).unwrap();
    writeln!( out, "wait_on_run synth_1" ).unwrap();
    writeln!( out ).unwrap();

    /* Report utilization */
    writeln!( out, "# Reports" ).unwrap();
    writeln!( out, "open_run synth_1" ).unwrap();
    writeln!( out, "report_utilization -file {project_name}_util.txt" ).unwrap();
    writeln!( out, "report_timing_summary -file {project_name}_timing.txt" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "puts \"c2v: synthesis complete for {mod_name} on {device_part}\"" ).unwrap();

    out
}

/* c2v_vivado_emit_ip_tcl generates a TCL script that packages the
   c2v module as a Vivado IP for use in block designs. The IP has
   AXI-Stream interfaces that Vivado's connection automation can wire. */

pub fn emit_ip_package_tcl(
    bound:        &BoundDfg,
    _device_part:  &str,
    vendor:       &str,
    version:      &str,
) -> String {
    let mut out = String::with_capacity( 4096 );
    let mod_name = super::verilog_safe_name( &bound.scheduled.dfg.name );

    writeln!( out, "# Generated by c2v — Vivado IP packaging script" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "ipx::package_project -root_dir . -vendor {vendor} \\" ).unwrap();
    writeln!( out, "    -library c2v -taxonomy /c2v -import_files" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "set_property name {mod_name} [ipx::current_core]" ).unwrap();
    writeln!( out, "set_property version {version} [ipx::current_core]" ).unwrap();
    writeln!( out, "set_property display_name \"c2v {mod_name}\" [ipx::current_core]" ).unwrap();
    writeln!( out, "set_property description \"Generated by c2v C-to-Verilog compiler\" [ipx::current_core]" ).unwrap();
    writeln!( out ).unwrap();

    /* Infer AXI-Stream interfaces */
    writeln!( out, "# Infer AXI-Stream interfaces" ).unwrap();
    writeln!( out, "ipx::infer_bus_interface s_axis_tdata  xilinx.com:interface:axis_rtl:1.0" ).unwrap();
    writeln!( out, "ipx::infer_bus_interface s_axis_tvalid xilinx.com:interface:axis_rtl:1.0" ).unwrap();
    writeln!( out, "ipx::infer_bus_interface s_axis_tready xilinx.com:interface:axis_rtl:1.0" ).unwrap();
    writeln!( out, "ipx::infer_bus_interface m_axis_tdata  xilinx.com:interface:axis_rtl:1.0" ).unwrap();
    writeln!( out, "ipx::infer_bus_interface m_axis_tvalid xilinx.com:interface:axis_rtl:1.0" ).unwrap();
    writeln!( out, "ipx::infer_bus_interface m_axis_tready xilinx.com:interface:axis_rtl:1.0" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "ipx::create_xgui_files [ipx::current_core]" ).unwrap();
    writeln!( out, "ipx::update_checksums [ipx::current_core]" ).unwrap();
    writeln!( out, "ipx::save_core [ipx::current_core]" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "puts \"c2v: IP packaged as {vendor}:c2v:{mod_name}:{version}\"" ).unwrap();

    out
}
