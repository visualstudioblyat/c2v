/* c2v_yosys_script generates complete Yosys synthesis scripts for
   different targets. Instead of a single synth command, this produces
   a multi-step script with proper optimization passes, technology
   mapping, and reporting — matching what a real FPGA engineer would
   write for production synthesis. */

use std::fmt::Write;

use crate::ir::BoundDfg;

pub fn emit_yosys_script(
    bound:       &BoundDfg,
    verilog_file: &str,
    target:       &str,
    output_json:  Option<&str>,
) -> String {
    let mut out = String::with_capacity( 4096 );
    let mod_name = super::verilog_safe_name( &bound.scheduled.dfg.name );

    writeln!( out, "# Generated by c2v — Yosys synthesis script" ).unwrap();
    writeln!( out, "# Target: {target}" ).unwrap();
    writeln!( out, "# Module: {mod_name}" ).unwrap();
    writeln!( out ).unwrap();

    /* Read source */
    writeln!( out, "read_verilog {verilog_file}" ).unwrap();
    writeln!( out ).unwrap();

    /* Generic optimization passes */
    writeln!( out, "# Optimization" ).unwrap();
    writeln!( out, "hierarchy -check -top {mod_name}" ).unwrap();
    writeln!( out, "proc" ).unwrap();
    writeln!( out, "opt" ).unwrap();
    writeln!( out, "fsm" ).unwrap();
    writeln!( out, "opt" ).unwrap();
    writeln!( out, "memory" ).unwrap();
    writeln!( out, "opt" ).unwrap();
    writeln!( out ).unwrap();

    /* Target-specific synthesis */
    let synth_cmd = match target {
        "xilinx" | "xc7" | "artix7" | "kintex7" | "ultrascale" | "alveo"
        | "xc7a35t" | "xc7a100t" | "xc7k325t" | "xcku040" | "xcvu9p" => {
            writeln!( out, "# Xilinx 7-series / UltraScale+" ).unwrap();
            "synth_xilinx -flatten"
        }
        "intel" | "altera" | "cyclonev" | "arria10" | "agilex"
        | "5cefa5" | "10ax115" | "agfb014" => {
            writeln!( out, "# Intel/Altera" ).unwrap();
            "synth_intel_alm -flatten"
        }
        "ice40" | "ice40up5k" | "ice40hx8k" => {
            writeln!( out, "# Lattice iCE40" ).unwrap();
            "synth_ice40 -flatten"
        }
        "ecp5" | "ecp5-25f" | "ecp5-85f" => {
            writeln!( out, "# Lattice ECP5" ).unwrap();
            "synth_ecp5 -flatten"
        }
        "crosslink" | "lifcl-17" => {
            writeln!( out, "# Lattice Nexus" ).unwrap();
            "synth_nexus -flatten"
        }
        _ => {
            writeln!( out, "# Generic synthesis" ).unwrap();
            "synth -flatten"
        }
    };
    writeln!( out, "{synth_cmd}" ).unwrap();
    writeln!( out ).unwrap();

    /* Reports */
    writeln!( out, "# Reports" ).unwrap();
    writeln!( out, "stat" ).unwrap();

    if let Some(json_path) = output_json {
        writeln!( out, "write_json {json_path}" ).unwrap();
    }

    writeln!( out ).unwrap();
    writeln!( out, "# Write output" ).unwrap();
    writeln!( out, "write_verilog -noattr {mod_name}_synth.v" ).unwrap();

    out
}

pub fn emit_nextpnr_script(
    bound:    &BoundDfg,
    target:   &str,
    json_in:  &str,
    freq_mhz: f64,
) -> String {
    let mut out = String::with_capacity( 2048 );
    let mod_name = super::verilog_safe_name( &bound.scheduled.dfg.name );

    writeln!( out, "#!/bin/bash" ).unwrap();
    writeln!( out, "# Generated by c2v — nextpnr place-and-route" ).unwrap();
    writeln!( out ).unwrap();

    let freq_str = format!( "{freq_mhz:.0}" );

    match target {
        "ice40" | "ice40up5k" => {
            writeln!( out, "nextpnr-ice40 \\" ).unwrap();
            writeln!( out, "    --up5k \\" ).unwrap();
            writeln!( out, "    --package sg48 \\" ).unwrap();
            writeln!( out, "    --json {json_in} \\" ).unwrap();
            writeln!( out, "    --asc {mod_name}.asc \\" ).unwrap();
            writeln!( out, "    --freq {freq_str} \\" ).unwrap();
            writeln!( out, "    --report {mod_name}_timing.json" ).unwrap();
            writeln!( out ).unwrap();
            writeln!( out, "icepack {mod_name}.asc {mod_name}.bin" ).unwrap();
        }
        "ice40hx8k" => {
            writeln!( out, "nextpnr-ice40 \\" ).unwrap();
            writeln!( out, "    --hx8k \\" ).unwrap();
            writeln!( out, "    --package ct256 \\" ).unwrap();
            writeln!( out, "    --json {json_in} \\" ).unwrap();
            writeln!( out, "    --asc {mod_name}.asc \\" ).unwrap();
            writeln!( out, "    --freq {freq_str}" ).unwrap();
        }
        "ecp5" | "ecp5-25f" => {
            writeln!( out, "nextpnr-ecp5 \\" ).unwrap();
            writeln!( out, "    --25k \\" ).unwrap();
            writeln!( out, "    --package CABGA256 \\" ).unwrap();
            writeln!( out, "    --json {json_in} \\" ).unwrap();
            writeln!( out, "    --textcfg {mod_name}.config \\" ).unwrap();
            writeln!( out, "    --freq {freq_str}" ).unwrap();
            writeln!( out ).unwrap();
            writeln!( out, "ecppack {mod_name}.config {mod_name}.bit" ).unwrap();
        }
        "ecp5-85f" => {
            writeln!( out, "nextpnr-ecp5 \\" ).unwrap();
            writeln!( out, "    --85k \\" ).unwrap();
            writeln!( out, "    --package CABGA554 \\" ).unwrap();
            writeln!( out, "    --json {json_in} \\" ).unwrap();
            writeln!( out, "    --textcfg {mod_name}.config \\" ).unwrap();
            writeln!( out, "    --freq {freq_str}" ).unwrap();
        }
        _ => {
            writeln!( out, "echo \"nextpnr not supported for target: {target}\"" ).unwrap();
        }
    }

    writeln!( out ).unwrap();
    writeln!( out, "echo \"c2v: place-and-route complete for {mod_name}\"" ).unwrap();

    out
}
