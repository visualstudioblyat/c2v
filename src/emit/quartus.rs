/* c2v_quartus generates Intel Quartus project files. The generated .tcl
   script creates a Quartus project targeting a specific Intel FPGA,
   adds the c2v Verilog sources, sets timing constraints, and runs
   synthesis. Supports Cyclone V, Arria 10, and Agilex devices.

   Usage: quartus_sh -t project.tcl */

use std::fmt::Write;

use crate::ir::BoundDfg;

/* c2v_quartus_emit_tcl generates a Quartus project creation TCL script.
   device_part is the Intel part number (e.g. "5CEFA5F23I7"). */

pub fn emit_quartus_tcl(
    bound:         &BoundDfg,
    device_part:   &str,
    device_family: &str,
    verilog_files: &[String],
    project_name:  &str,
    freq_mhz:      f64,
) -> String {
    let mut out = String::with_capacity( 4096 );
    let mod_name = super::verilog_safe_name( &bound.scheduled.dfg.name );

    writeln!( out, "# Generated by c2v — Quartus project script" ).unwrap();
    writeln!( out, "# Run: quartus_sh -t {project_name}.tcl" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "package require ::quartus::project" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "project_new {project_name} -overwrite" ).unwrap();
    writeln!( out ).unwrap();

    /* Device assignment */
    writeln!( out, "set_global_assignment -name FAMILY \"{device_family}\"" ).unwrap();
    writeln!( out, "set_global_assignment -name DEVICE {device_part}" ).unwrap();
    writeln!( out, "set_global_assignment -name TOP_LEVEL_ENTITY {mod_name}" ).unwrap();
    writeln!( out ).unwrap();

    /* Add source files */
    for f in verilog_files {
        writeln!( out, "set_global_assignment -name VERILOG_FILE {f}" ).unwrap();
    }
    writeln!( out ).unwrap();

    /* Timing constraints (SDC) */
    let period_ns = 1000.0 / freq_mhz;
    writeln!( out, "# Timing constraints" ).unwrap();
    writeln!( out, "set_global_assignment -name SDC_FILE {project_name}.sdc" ).unwrap();
    writeln!( out ).unwrap();

    /* Generate SDC file content */
    writeln!( out, "# Write SDC file" ).unwrap();
    writeln!( out, "set sdc_fd [open \"{project_name}.sdc\" w]" ).unwrap();
    writeln!( out, "puts $sdc_fd \"create_clock -period {period_ns:.3} -name clk \\[get_ports {{clk}}\\]\"" ).unwrap();
    writeln!( out, "puts $sdc_fd \"derive_pll_clocks\"" ).unwrap();
    writeln!( out, "puts $sdc_fd \"derive_clock_uncertainty\"" ).unwrap();
    writeln!( out, "close $sdc_fd" ).unwrap();
    writeln!( out ).unwrap();

    /* Optimization settings */
    writeln!( out, "# Optimization" ).unwrap();
    writeln!( out, "set_global_assignment -name OPTIMIZATION_MODE \"HIGH PERFORMANCE EFFORT\"" ).unwrap();
    writeln!( out, "set_global_assignment -name ALLOW_REGISTER_RETIMING ON" ).unwrap();
    writeln!( out ).unwrap();

    /* Compile */
    writeln!( out, "# Compile" ).unwrap();
    writeln!( out, "package require ::quartus::flow" ).unwrap();
    writeln!( out, "execute_flow -compile" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "project_close" ).unwrap();
    writeln!( out, "puts \"c2v: Quartus compilation complete for {mod_name} on {device_part}\"" ).unwrap();

    out
}

/* c2v_quartus_emit_qsys generates a Platform Designer (Qsys) component
   definition for the c2v module with Avalon-ST interfaces. */

pub fn emit_qsys_component(
    bound: &BoundDfg,
) -> String {
    let mut out = String::with_capacity( 2048 );
    let dfg      = &bound.scheduled.dfg;
    let mod_name = super::verilog_safe_name( &dfg.name );
    let in_width:  u32 = dfg.inputs.iter().map( |p| p.width ).sum();
    let out_width: u32 = dfg.outputs.iter().map( |p| p.width ).sum();

    writeln!( out, "# Generated by c2v — Qsys/Platform Designer component" ).unwrap();
    writeln!( out, "package require -exact qsys 16.0" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "create_system {mod_name}" ).unwrap();
    writeln!( out, "set_project_property DEVICE_FAMILY {{Cyclone V}}" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "add_instance {mod_name}_0 {mod_name}" ).unwrap();
    writeln!( out ).unwrap();

    /* Avalon-ST sink */
    writeln!( out, "add_interface sink avalon_streaming sink" ).unwrap();
    writeln!( out, "set_interface_property sink dataBitsPerSymbol {in_width}" ).unwrap();
    writeln!( out ).unwrap();

    /* Avalon-ST source */
    writeln!( out, "add_interface source avalon_streaming source" ).unwrap();
    writeln!( out, "set_interface_property source dataBitsPerSymbol {out_width}" ).unwrap();
    writeln!( out ).unwrap();

    writeln!( out, "save_system {mod_name}.qsys" ).unwrap();

    out
}
