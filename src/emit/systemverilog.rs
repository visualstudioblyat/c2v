/* c2v_systemverilog emits SystemVerilog instead of Verilog-2001.
   SystemVerilog adds: logic type (replaces reg/wire), always_ff/
   always_comb blocks, typedef enum for FSM states, and package
   imports. This produces cleaner RTL that modern tools prefer. */

use std::fmt::Write;

use crate::ir::{BoundDfg, DfgOp, NodeId};
use super::{build_signal_names, get_inputs, verilog_safe_name, verilog_binop, state_width, is_port_signed};

pub fn emit_systemverilog( bound: &BoundDfg ) -> String {
    let mut out = String::with_capacity( 8192 );
    let dfg       = &bound.scheduled.dfg;
    let sig_names = build_signal_names( bound );
    let total_cyc = bound.scheduled.total_cycles;
    let sb        = state_width( total_cyc );

    writeln!( out, "// Generated by c2v — SystemVerilog" ).unwrap();
    writeln!( out, "// Function: {}", dfg.name ).unwrap();
    writeln!( out, "// Latency:  {total_cyc} cycles" ).unwrap();
    writeln!( out ).unwrap();

    let name = verilog_safe_name( &dfg.name );

    /* Module header */
    writeln!( out, "module {name} (" ).unwrap();
    writeln!( out, "    input  logic              clk," ).unwrap();
    writeln!( out, "    input  logic              rst," ).unwrap();
    writeln!( out, "    input  logic              start," ).unwrap();
    writeln!( out, "    output logic              done," ).unwrap();

    for port in &dfg.inputs {
        let wd   = sv_width( port.width );
        let sign = if is_port_signed( &port.name, dfg ) { "signed " } else { "" };
        writeln!( out, "    input  logic {sign}{wd}{},", verilog_safe_name(&port.name) ).unwrap();
    }
    for (i, port) in dfg.outputs.iter().enumerate() {
        let wd    = sv_width( port.width );
        let sign  = if is_port_signed( &port.name, dfg ) { "signed " } else { "" };
        let comma = if i == dfg.outputs.len() - 1 { "" } else { "," };
        writeln!( out, "    output logic {sign}{wd}{}{comma}", verilog_safe_name(&port.name) ).unwrap();
    }
    writeln!( out, ");" ).unwrap();
    writeln!( out ).unwrap();

    /* FSM typedef enum */
    writeln!( out, "    typedef enum logic [{sb}:0] {{", sb = sb - 1 ).unwrap();
    write!( out, "        S_IDLE" ).unwrap();
    for c in 0..total_cyc {
        write!( out, ", S_C{c}" ).unwrap();
    }
    writeln!( out, ", S_DONE" ).unwrap();
    writeln!( out, "    }} state_t;" ).unwrap();
    writeln!( out, "    state_t {name}_state;" ).unwrap();
    writeln!( out ).unwrap();

    /* Memory arrays */
    if !dfg.arrays.is_empty() {
        for arr in &dfg.arrays {
            let wd   = sv_width( arr.elem_width );
            let aname = verilog_safe_name( &format!("mem_{}", arr.name) );
            writeln!( out, "    logic {wd}{aname} [0:{}];", arr.size - 1 ).unwrap();
        }
        writeln!( out ).unwrap();
    }

    /* Datapath signals */
    for node in &dfg.nodes {
        match &node.op {
            DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Output(_) | DfgOp::Nop => {}
            _ => {
                if let Some(sig) = sig_names.get( &node.id ) {
                    let wd   = sv_width( node.width );
                    let sign = if node.signed { "signed " } else { "" };
                    writeln!( out, "    logic {sign}{wd}{sig};" ).unwrap();
                }
            }
        }
    }
    writeln!( out ).unwrap();

    /* always_ff block */
    writeln!( out, "    always_ff @(posedge clk) begin" ).unwrap();
    writeln!( out, "        if (rst) begin" ).unwrap();
    writeln!( out, "            {name}_state <= S_IDLE;" ).unwrap();
    writeln!( out, "            done         <= 1'b0;" ).unwrap();
    writeln!( out, "        end else begin" ).unwrap();
    writeln!( out, "            unique case ({name}_state)" ).unwrap();

    /* IDLE */
    writeln!( out, "                S_IDLE: begin" ).unwrap();
    writeln!( out, "                    if (start) begin" ).unwrap();
    writeln!( out, "                        done         <= 1'b0;" ).unwrap();
    writeln!( out, "                        {name}_state <= S_C0;" ).unwrap();
    writeln!( out, "                    end" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    /* Cycle states */
    for cycle in 0..total_cyc {
        writeln!( out, "                S_C{cycle}: begin" ).unwrap();

        for node in &dfg.nodes {
            if bound.scheduled.schedule.get( &node.id ) != Some( &cycle ) { continue; }

            match &node.op {
                DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop => {}
                DfgOp::Output(oname) => {
                    let inputs = get_inputs( node.id, bound );
                    if let Some(&src) = inputs.first() {
                        writeln!( out, "                    {} <= {};",
                            verilog_safe_name(oname),
                            sv_operand(src, &sig_names, bound) ).unwrap();
                    }
                }
                DfgOp::Not => {
                    let inputs = get_inputs( node.id, bound );
                    if let Some(&a) = inputs.first() {
                        let sig = &sig_names[&node.id];
                        writeln!( out, "                    {sig} <= ~{};",
                            sv_operand(a, &sig_names, bound) ).unwrap();
                    }
                }
                DfgOp::Mux => {
                    let inputs = get_inputs( node.id, bound );
                    if inputs.len() >= 3 {
                        let sig = &sig_names[&node.id];
                        writeln!( out, "                    {sig} <= {} ? {} : {};",
                            sv_operand(inputs[0], &sig_names, bound),
                            sv_operand(inputs[1], &sig_names, bound),
                            sv_operand(inputs[2], &sig_names, bound) ).unwrap();
                    }
                }
                DfgOp::Load { array } => {
                    let inputs = get_inputs( node.id, bound );
                    let sig = &sig_names[&node.id];
                    let arr = verilog_safe_name( &format!("mem_{array}") );
                    if let Some(&idx) = inputs.iter().find(|&&id| {
                        bound.scheduled.dfg.edges.iter().any(|e| e.from == id && e.to == node.id && e.width > 0)
                    }) {
                        writeln!( out, "                    {sig} <= {arr}[{}];",
                            sv_operand(idx, &sig_names, bound) ).unwrap();
                    }
                }
                DfgOp::Store { array } => {
                    let inputs = get_inputs( node.id, bound );
                    let arr = verilog_safe_name( &format!("mem_{array}") );
                    if inputs.len() >= 2 {
                        writeln!( out, "                    {arr}[{}] <= {};",
                            sv_operand(inputs[0], &sig_names, bound),
                            sv_operand(inputs[1], &sig_names, bound) ).unwrap();
                    }
                }
                _ => {
                    if let Some(op_str) = verilog_binop( &node.op ) {
                        let inputs = get_inputs( node.id, bound );
                        if inputs.len() >= 2 {
                            let sig = &sig_names[&node.id];
                            writeln!( out, "                    {sig} <= {} {} {};",
                                sv_operand(inputs[0], &sig_names, bound),
                                op_str,
                                sv_operand(inputs[1], &sig_names, bound) ).unwrap();
                        }
                    }
                }
            }
        }

        let next = if cycle + 1 < total_cyc {
            format!( "S_C{}", cycle + 1 )
        } else {
            "S_DONE".to_string()
        };
        writeln!( out, "                    {name}_state <= {next};" ).unwrap();
        writeln!( out, "                end" ).unwrap();
    }

    /* DONE */
    writeln!( out, "                S_DONE: begin" ).unwrap();
    writeln!( out, "                    done         <= 1'b1;" ).unwrap();
    writeln!( out, "                    {name}_state <= S_IDLE;" ).unwrap();
    writeln!( out, "                end" ).unwrap();

    writeln!( out, "                default: {name}_state <= S_IDLE;" ).unwrap();
    writeln!( out, "            endcase" ).unwrap();
    writeln!( out, "        end" ).unwrap();
    writeln!( out, "    end" ).unwrap();
    writeln!( out ).unwrap();
    writeln!( out, "endmodule" ).unwrap();

    out
}

fn sv_width( bits: u32 ) -> String {
    if bits <= 1 { String::new() } else { format!( "[{}:0] ", bits - 1 ) }
}

fn sv_operand( id: NodeId, sig_names: &std::collections::HashMap<NodeId, String>, bound: &BoundDfg ) -> String {
    let node = &bound.scheduled.dfg.nodes[id as usize];
    match &node.op {
        DfgOp::Input(name) => verilog_safe_name( name ),
        DfgOp::Const(val)  => format!( "{}'d{val}", node.width ),
        _ => sig_names.get(&id).cloned().unwrap_or_else( || format!("node_{id}") ),
    }
}
