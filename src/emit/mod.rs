pub mod pipeline;

use std::collections::HashMap;
use std::fmt::Write;

use crate::ir::{BoundDfg, DfgOp, NodeId};

pub fn emit_verilog(bound: &BoundDfg) -> String {
    let mut out = String::with_capacity(8192);
    let dfg = &bound.scheduled.dfg;

    let sig_names = build_signal_names(bound);

    writeln!(out, "// Generated by c2v — Firedancer-style C to Verilog").unwrap();
    writeln!(out, "// Source function: {}", dfg.name).unwrap();
    writeln!(out, "// Schedule: {} cycles", bound.scheduled.total_cycles).unwrap();
    writeln!(out, "// Resources: {} units", bound.resources.len()).unwrap();
    writeln!(out).unwrap();

    // Module declaration
    write!(out, "module {name}(\n", name = verilog_safe_name(&dfg.name)).unwrap();
    writeln!(out, "    input  wire              clk,").unwrap();
    writeln!(out, "    input  wire              rst,").unwrap();
    writeln!(out, "    input  wire              start,").unwrap();
    writeln!(out, "    output reg               done,").unwrap();

    for port in &dfg.inputs {
        let wd = width_decl(port.width);
        writeln!(out, "    input  wire {wd}{},", verilog_safe_name(&port.name)).unwrap();
    }

    for (idx, port) in dfg.outputs.iter().enumerate() {
        let wd = width_decl(port.width);
        let comma = if idx == dfg.outputs.len() - 1 { "" } else { "," };
        writeln!(
            out,
            "    output reg  {wd}{}{comma}",
            verilog_safe_name(&port.name)
        )
        .unwrap();
    }

    writeln!(out, ");").unwrap();
    writeln!(out).unwrap();

    // FSM state encoding
    let state_bits = state_width(bound.scheduled.total_cycles);
    writeln!(out, "    // FSM states").unwrap();
    writeln!(out, "    localparam [{sb}:0] S_IDLE = {state_bits}'d0;", sb = state_bits - 1)
        .unwrap();
    for cycle in 0..bound.scheduled.total_cycles {
        writeln!(
            out,
            "    localparam [{sb}:0] S_C{cycle} = {state_bits}'d{v};",
            sb = state_bits - 1,
            v = cycle + 1
        )
        .unwrap();
    }
    writeln!(
        out,
        "    localparam [{sb}:0] S_DONE = {state_bits}'d{v};",
        sb = state_bits - 1,
        v = bound.scheduled.total_cycles + 1
    )
    .unwrap();
    writeln!(out).unwrap();
    writeln!(out, "    reg [{sb}:0] state;", sb = state_bits - 1).unwrap();
    writeln!(out).unwrap();

    // Memory arrays (BRAM inference)
    if !dfg.arrays.is_empty() {
        writeln!(out, "    // Memory arrays").unwrap();
        for arr in &dfg.arrays {
            let wd = width_decl(arr.elem_width);
            let name = verilog_safe_name(&format!("mem_{}", arr.name));
            writeln!(out, "    reg  {wd}{name} [0:{}];", arr.size - 1).unwrap();
        }
        writeln!(out).unwrap();
    }

    // Datapath registers — only for intermediate computation nodes
    writeln!(out, "    // Datapath registers").unwrap();
    for node in &dfg.nodes {
        match &node.op {
            DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Output(_) | DfgOp::Nop => {}
            _ => {
                let sig = &sig_names[&node.id];
                let wd = width_decl(node.width);
                writeln!(out, "    reg  {wd}{sig};").unwrap();
            }
        }
    }
    writeln!(out).unwrap();

    // FSM body
    writeln!(out, "    always @(posedge clk) begin").unwrap();
    writeln!(out, "        if (rst) begin").unwrap();
    writeln!(out, "            state <= S_IDLE;").unwrap();
    writeln!(out, "            done  <= 1'b0;").unwrap();
    writeln!(out, "        end else begin").unwrap();
    writeln!(out, "            case (state)").unwrap();

    // IDLE state — done stays high until next start
    writeln!(out, "                S_IDLE: begin").unwrap();
    writeln!(out, "                    if (start) begin").unwrap();
    writeln!(out, "                        done <= 1'b0;").unwrap();
    writeln!(out, "                        state <= S_C0;").unwrap();
    writeln!(out, "                    end").unwrap();
    writeln!(out, "                end").unwrap();

    // Cycle states
    for cycle in 0..bound.scheduled.total_cycles {
        writeln!(out, "                S_C{cycle}: begin").unwrap();

        // Emit all operations scheduled in this cycle
        for node in &dfg.nodes {
            if bound.scheduled.schedule.get(&node.id) != Some(&cycle) {
                continue;
            }
            match &node.op {
                DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Nop => {}
                DfgOp::Output(name) => {
                    let inputs = get_inputs(node.id, bound);
                    if let Some(&src) = inputs.first() {
                        let src_sig = operand_ref(src, &sig_names, bound);
                        writeln!(
                            out,
                            "                    {out_name} <= {src_sig};",
                            out_name = verilog_safe_name(name)
                        )
                        .unwrap();
                    }
                }
                DfgOp::Not => {
                    let inputs = get_inputs(node.id, bound);
                    if let Some(&a) = inputs.first() {
                        let sig = &sig_names[&node.id];
                        let a_ref = operand_ref(a, &sig_names, bound);
                        writeln!(out, "                    {sig} <= ~{a_ref};").unwrap();
                    }
                }
                DfgOp::Mux => {
                    let inputs = get_inputs(node.id, bound);
                    if inputs.len() >= 3 {
                        let sig = &sig_names[&node.id];
                        let cond = operand_ref(inputs[0], &sig_names, bound);
                        let t_val = operand_ref(inputs[1], &sig_names, bound);
                        let f_val = operand_ref(inputs[2], &sig_names, bound);
                        writeln!(
                            out,
                            "                    {sig} <= {cond} ? {t_val} : {f_val};"
                        )
                        .unwrap();
                    }
                }
                DfgOp::Load { array } => {
                    let inputs = get_inputs(node.id, bound);
                    let sig = &sig_names[&node.id];
                    let arr_name = verilog_safe_name(&format!("mem_{array}"));
                    if let Some(&idx) = inputs.iter().find(|&&id| {
                        bound.scheduled.dfg.edges.iter().any(|e| e.from == id && e.to == node.id && e.width > 0)
                    }) {
                        let idx_ref = operand_ref(idx, &sig_names, bound);
                        writeln!(out, "                    {sig} <= {arr_name}[{idx_ref}];").unwrap();
                    }
                }
                DfgOp::Store { array } => {
                    let inputs = get_inputs(node.id, bound);
                    let arr_name = verilog_safe_name(&format!("mem_{array}"));
                    if inputs.len() >= 2 {
                        let idx_ref = operand_ref(inputs[0], &sig_names, bound);
                        let val_ref = operand_ref(inputs[1], &sig_names, bound);
                        writeln!(out, "                    {arr_name}[{idx_ref}] <= {val_ref};").unwrap();
                    }
                }
                _ => {
                    if let Some(op_str) = verilog_binop(&node.op) {
                        let inputs = get_inputs(node.id, bound);
                        if inputs.len() >= 2 {
                            let sig = &sig_names[&node.id];
                            let left = operand_ref(inputs[0], &sig_names, bound);
                            let right = operand_ref(inputs[1], &sig_names, bound);
                            writeln!(
                                out,
                                "                    {sig} <= {left} {op_str} {right};"
                            )
                            .unwrap();
                        }
                    }
                }
            }
        }

        let next = if cycle + 1 < bound.scheduled.total_cycles {
            format!("S_C{}", cycle + 1)
        } else {
            "S_DONE".to_string()
        };
        writeln!(out, "                    state <= {next};").unwrap();
        writeln!(out, "                end").unwrap();
    }

    // DONE state
    writeln!(out, "                S_DONE: begin").unwrap();
    writeln!(out, "                    done  <= 1'b1;").unwrap();
    writeln!(out, "                    state <= S_IDLE;").unwrap();
    writeln!(out, "                end").unwrap();
    writeln!(out, "                default: state <= S_IDLE;").unwrap();
    writeln!(out, "            endcase").unwrap();
    writeln!(out, "        end").unwrap();
    writeln!(out, "    end").unwrap();
    writeln!(out).unwrap();
    writeln!(out, "endmodule").unwrap();

    out
}

pub(crate) fn build_signal_names(bound: &BoundDfg) -> HashMap<NodeId, String> {
    let dfg = &bound.scheduled.dfg;
    let mut names: HashMap<NodeId, String> = HashMap::new();
    let mut name_counts: HashMap<String, u32> = HashMap::new();

    for node in &dfg.nodes {
        let base = match &node.op {
            DfgOp::Input(_) => continue,
            DfgOp::Const(_) => continue,
            DfgOp::Output(_) => continue,
            DfgOp::Nop => continue,
            DfgOp::Add => "add".to_string(),
            DfgOp::Sub => "sub".to_string(),
            DfgOp::Mul => "mul".to_string(),
            DfgOp::Div => "div".to_string(),
            DfgOp::Mod => "mod_r".to_string(),
            DfgOp::Shl => "shl".to_string(),
            DfgOp::Shr => "shr".to_string(),
            DfgOp::And => "band".to_string(),
            DfgOp::Or => "bor".to_string(),
            DfgOp::Xor => "bxor".to_string(),
            DfgOp::Not => "bnot".to_string(),
            DfgOp::Eq => "eq".to_string(),
            DfgOp::Ne => "ne".to_string(),
            DfgOp::Lt => "lt".to_string(),
            DfgOp::Gt => "gt".to_string(),
            DfgOp::Le => "le".to_string(),
            DfgOp::Ge => "ge".to_string(),
            DfgOp::Mux => "mux".to_string(),
            DfgOp::Reg => "reg".to_string(),
            DfgOp::Load { array } => format!("ld_{array}"),
            DfgOp::Store { array } => format!("st_{array}"),
            DfgOp::FieldGet { struct_name: _, field } => format!("fg_{field}"),
            DfgOp::FieldSet { struct_name: _, field } => format!("fs_{field}"),
        };

        let count = name_counts.entry(base.clone()).or_insert(0);
        let sig_name = if *count == 0 {
            base.clone()
        } else {
            format!("{base}_{count}")
        };
        *count += 1;
        names.insert(node.id, sig_name);
    }

    names
}

pub(crate) fn operand_ref(node_id: NodeId, sig_names: &HashMap<NodeId, String>, bound: &BoundDfg) -> String {
    let node = &bound.scheduled.dfg.nodes[node_id as usize];
    match &node.op {
        DfgOp::Input(name) => verilog_safe_name(name),
        DfgOp::Const(val) => {
            let w = node.width;
            format!("{w}'d{val}")
        }
        _ => sig_names
            .get(&node_id)
            .cloned()
            .unwrap_or_else(|| format!("node_{node_id}")),
    }
}

pub(crate) fn get_inputs(node_id: NodeId, bound: &BoundDfg) -> Vec<NodeId> {
    bound
        .scheduled
        .dfg
        .edges
        .iter()
        .filter(|e| e.to == node_id)
        .map(|e| e.from)
        .collect()
}

pub(crate) fn verilog_binop(op: &DfgOp) -> Option<&'static str> {
    match op {
        DfgOp::Add => Some("+"),
        DfgOp::Sub => Some("-"),
        DfgOp::Mul => Some("*"),
        DfgOp::Div => Some("/"),
        DfgOp::Mod => Some("%"),
        DfgOp::Shl => Some("<<"),
        DfgOp::Shr => Some(">>"),
        DfgOp::And => Some("&"),
        DfgOp::Or => Some("|"),
        DfgOp::Xor => Some("^"),
        DfgOp::Eq => Some("=="),
        DfgOp::Ne => Some("!="),
        DfgOp::Lt => Some("<"),
        DfgOp::Gt => Some(">"),
        DfgOp::Le => Some("<="),
        DfgOp::Ge => Some(">="),
        _ => None,
    }
}

pub(crate) fn verilog_safe_name(name: &str) -> String {
    const RESERVED: &[&str] = &[
        "module", "endmodule", "input", "output", "inout", "wire", "reg", "integer", "real",
        "time", "parameter", "localparam", "assign", "always", "initial", "begin", "end", "if",
        "else", "case", "endcase", "default", "for", "while", "repeat", "forever", "fork",
        "join", "task", "endtask", "function", "endfunction", "return", "generate",
        "endgenerate", "posedge", "negedge", "or", "and", "not", "xor", "buf", "supply0",
        "supply1", "tri", "wand", "wor", "table", "endtable", "event",
        "signed", "unsigned", "specify", "endspecify", "primitive", "endprimitive",
        "state", "clk", "rst", "done", "start", "valid_in", "valid_out", "valid_sr",
        "valid_pipe",
    ];

    let sanitized: String = name
        .chars()
        .map(|c| if c.is_alphanumeric() || c == '_' { c } else { '_' })
        .collect();

    if RESERVED.contains(&sanitized.as_str()) || sanitized.starts_with(|c: char| c.is_ascii_digit())
    {
        format!("s_{sanitized}")
    } else {
        sanitized
    }
}

pub(crate) fn width_decl(bits: u32) -> String {
    if bits <= 1 {
        "              ".to_string()
    } else {
        format!("[{:>2}:0] ", bits - 1)
    }
}

pub(crate) fn state_width(total_cycles: u32) -> u32 {
    let states = total_cycles + 2;
    (32 - states.leading_zeros()).max(1)
}
