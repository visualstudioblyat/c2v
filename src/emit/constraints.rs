use std::fmt::Write;

use crate::ir::BoundDfg;

pub fn emit_xilinx_xdc(bound: &BoundDfg, target_freq_mhz: f64) -> String {
    let mut out = String::with_capacity(2048);
    let dfg = &bound.scheduled.dfg;
    let period_ns = 1000.0 / target_freq_mhz;

    writeln!(out, "# Generated by c2v — Xilinx Design Constraints").unwrap();
    writeln!(out, "# Function: {}", dfg.name).unwrap();
    writeln!(out, "# Target frequency: {target_freq_mhz} MHz ({period_ns:.3} ns period)").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "create_clock -period {period_ns:.3} -name clk [get_ports clk]").unwrap();
    writeln!(out).unwrap();

    writeln!(out, "# Input/output delay constraints (assume 25% of period)").unwrap();
    let io_delay = period_ns * 0.25;
    for port in &dfg.inputs {
        let name = super::verilog_safe_name(&port.name);
        writeln!(out, "set_input_delay -clock clk {io_delay:.3} [get_ports {name}]").unwrap();
    }
    for port in &dfg.outputs {
        let name = super::verilog_safe_name(&port.name);
        writeln!(out, "set_output_delay -clock clk {io_delay:.3} [get_ports {name}]").unwrap();
    }
    writeln!(out).unwrap();

    writeln!(out, "set_input_delay -clock clk {io_delay:.3} [get_ports start]").unwrap();
    writeln!(out, "set_output_delay -clock clk {io_delay:.3} [get_ports done]").unwrap();

    out
}

pub fn emit_intel_sdc(bound: &BoundDfg, target_freq_mhz: f64) -> String {
    let mut out = String::with_capacity(2048);
    let dfg = &bound.scheduled.dfg;
    let period_ns = 1000.0 / target_freq_mhz;

    writeln!(out, "# Generated by c2v — Intel/Quartus Timing Constraints").unwrap();
    writeln!(out, "# Function: {}", dfg.name).unwrap();
    writeln!(out).unwrap();

    writeln!(out, "create_clock -name clk -period {period_ns:.3} [get_ports {{clk}}]").unwrap();
    writeln!(out, "derive_pll_clocks").unwrap();
    writeln!(out, "derive_clock_uncertainty").unwrap();
    writeln!(out).unwrap();

    let io_delay = period_ns * 0.25;
    for port in &dfg.inputs {
        let name = super::verilog_safe_name(&port.name);
        writeln!(out, "set_input_delay -clock clk {io_delay:.3} [get_ports {{{name}[*]}}]").unwrap();
    }
    for port in &dfg.outputs {
        let name = super::verilog_safe_name(&port.name);
        writeln!(out, "set_output_delay -clock clk {io_delay:.3} [get_ports {{{name}[*]}}]").unwrap();
    }

    out
}
