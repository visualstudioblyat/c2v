use std::fmt::Write;

use crate::ir::{BoundDfg, DfgOp, NodeId};
use super::{build_signal_names, get_inputs, verilog_safe_name, width_decl};

pub fn emit_rtlil(bound: &BoundDfg) -> String {
    let mut out = String::with_capacity(8192);
    let dfg = &bound.scheduled.dfg;
    let sig_names = build_signal_names(bound);

    writeln!(out, "# Generated by c2v — RTLIL for Yosys").unwrap();
    writeln!(out, "# Function: {}", dfg.name).unwrap();
    writeln!(out).unwrap();

    let mod_name = verilog_safe_name(&dfg.name);
    writeln!(out, "autoidx 1").unwrap();
    writeln!(out, "module \\{mod_name}").unwrap();

    // Ports
    writeln!(out, "  wire width 1 input 0 \\clk").unwrap();
    writeln!(out, "  wire width 1 input 1 \\rst").unwrap();
    writeln!(out, "  wire width 1 input 2 \\start").unwrap();
    writeln!(out, "  wire width 1 output 3 \\done").unwrap();

    let mut port_idx = 4;
    for port in &dfg.inputs {
        let name = verilog_safe_name(&port.name);
        writeln!(out, "  wire width {} input {} \\{name}", port.width, port_idx).unwrap();
        port_idx += 1;
    }
    for port in &dfg.outputs {
        let name = verilog_safe_name(&port.name);
        writeln!(out, "  wire width {} output {} \\{name}", port.width, port_idx).unwrap();
        port_idx += 1;
    }

    // Internal wires
    for node in &dfg.nodes {
        match &node.op {
            DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Output(_) | DfgOp::Nop => {}
            _ => {
                if let Some(sig) = sig_names.get(&node.id) {
                    writeln!(out, "  wire width {} \\{sig}", node.width).unwrap();
                }
            }
        }
    }
    writeln!(out).unwrap();

    // Cells for each operation
    for node in &dfg.nodes {
        let inputs = get_inputs(node.id, bound);
        match &node.op {
            DfgOp::Input(_) | DfgOp::Const(_) | DfgOp::Output(_) | DfgOp::Nop => {}
            DfgOp::Add => emit_cell(&mut out, &sig_names, bound, node.id, "$add", &inputs, node.width),
            DfgOp::Sub => emit_cell(&mut out, &sig_names, bound, node.id, "$sub", &inputs, node.width),
            DfgOp::Mul => emit_cell(&mut out, &sig_names, bound, node.id, "$mul", &inputs, node.width),
            DfgOp::And => emit_cell(&mut out, &sig_names, bound, node.id, "$and", &inputs, node.width),
            DfgOp::Or => emit_cell(&mut out, &sig_names, bound, node.id, "$or", &inputs, node.width),
            DfgOp::Xor => emit_cell(&mut out, &sig_names, bound, node.id, "$xor", &inputs, node.width),
            DfgOp::Shl => emit_cell(&mut out, &sig_names, bound, node.id, "$shl", &inputs, node.width),
            DfgOp::Shr => emit_cell(&mut out, &sig_names, bound, node.id, "$shr", &inputs, node.width),
            DfgOp::Eq => emit_cell(&mut out, &sig_names, bound, node.id, "$eq", &inputs, 1),
            DfgOp::Ne => emit_cell(&mut out, &sig_names, bound, node.id, "$ne", &inputs, 1),
            DfgOp::Lt => emit_cell(&mut out, &sig_names, bound, node.id, "$lt", &inputs, 1),
            DfgOp::Gt => emit_cell(&mut out, &sig_names, bound, node.id, "$gt", &inputs, 1),
            DfgOp::Le => emit_cell(&mut out, &sig_names, bound, node.id, "$le", &inputs, 1),
            DfgOp::Ge => emit_cell(&mut out, &sig_names, bound, node.id, "$ge", &inputs, 1),
            DfgOp::Not => {
                if let Some(sig) = sig_names.get(&node.id) {
                    if let Some(&a) = inputs.first() {
                        let a_ref = operand_ref_rtlil(a, &sig_names, bound);
                        writeln!(out, "  cell $not \\{sig}_cell").unwrap();
                        writeln!(out, "    parameter \\A_WIDTH {}", node.width).unwrap();
                        writeln!(out, "    parameter \\Y_WIDTH {}", node.width).unwrap();
                        writeln!(out, "    connect \\A {a_ref}").unwrap();
                        writeln!(out, "    connect \\Y \\{sig}").unwrap();
                        writeln!(out, "  end").unwrap();
                    }
                }
            }
            DfgOp::Mux => {
                if let Some(sig) = sig_names.get(&node.id) {
                    if inputs.len() >= 3 {
                        let s = operand_ref_rtlil(inputs[0], &sig_names, bound);
                        let a = operand_ref_rtlil(inputs[2], &sig_names, bound);
                        let b = operand_ref_rtlil(inputs[1], &sig_names, bound);
                        writeln!(out, "  cell $mux \\{sig}_cell").unwrap();
                        writeln!(out, "    parameter \\WIDTH {}", node.width).unwrap();
                        writeln!(out, "    connect \\A {a}").unwrap();
                        writeln!(out, "    connect \\B {b}").unwrap();
                        writeln!(out, "    connect \\S {s}").unwrap();
                        writeln!(out, "    connect \\Y \\{sig}").unwrap();
                        writeln!(out, "  end").unwrap();
                    }
                }
            }
            _ => {}
        }
    }

    writeln!(out, "end").unwrap();
    out
}

fn emit_cell(
    out: &mut String,
    sig_names: &std::collections::HashMap<NodeId, String>,
    bound: &BoundDfg,
    node_id: NodeId,
    cell_type: &str,
    inputs: &[NodeId],
    width: u32,
) {
    if let Some(sig) = sig_names.get(&node_id) {
        if inputs.len() >= 2 {
            let a = operand_ref_rtlil(inputs[0], sig_names, bound);
            let b = operand_ref_rtlil(inputs[1], sig_names, bound);
            writeln!(out, "  cell {cell_type} \\{sig}_cell").unwrap();
            writeln!(out, "    parameter \\A_WIDTH {width}").unwrap();
            writeln!(out, "    parameter \\B_WIDTH {width}").unwrap();
            writeln!(out, "    parameter \\Y_WIDTH {width}").unwrap();
            writeln!(out, "    parameter \\A_SIGNED 0").unwrap();
            writeln!(out, "    parameter \\B_SIGNED 0").unwrap();
            writeln!(out, "    connect \\A {a}").unwrap();
            writeln!(out, "    connect \\B {b}").unwrap();
            writeln!(out, "    connect \\Y \\{sig}").unwrap();
            writeln!(out, "  end").unwrap();
        }
    }
}

fn operand_ref_rtlil(
    node_id: NodeId,
    sig_names: &std::collections::HashMap<NodeId, String>,
    bound: &BoundDfg,
) -> String {
    let node = &bound.scheduled.dfg.nodes[node_id as usize];
    match &node.op {
        DfgOp::Input(name) => format!("\\{}", verilog_safe_name(name)),
        DfgOp::Const(val) => format!("{}'d{}", node.width, val),
        _ => sig_names.get(&node_id)
            .map(|s| format!("\\{s}"))
            .unwrap_or_else(|| format!("\\node_{node_id}")),
    }
}
